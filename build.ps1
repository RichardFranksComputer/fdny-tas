# build.ps1 -- build FDNYCore.asi (32-bit PE DLL) with the bundled zig toolchain.
#   .\build.ps1                    # Debug and Release
#   .\build.ps1 -Config Release
#   .\build.ps1 -Without glitch,tp # leave feature modules out (folders features\<name>\)
#   .\build.ps1 -Without *         # the core services alone
# Output: build\<Config>\FDNYCore.asi (with -Without: build\<Config>-without\)
# Freestanding: no CRT, imports kernel32/user32/gdi32/bcrypt only
# (gdi32: the hud_glitch box is rendered with GDI, item 11d).

# Every build writes build\<Config>\quick-reference.md: the player reference (tools\docgen.py) for that source.
# Releases are built by .github/workflows/release.yml from this script, not from a local build (D45).

param([ValidateSet('Debug', 'Release', 'Both')] [string]$Config = 'Both',
      [string[]]$Without = @())

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
# Zig and Python: the VM's local tools (environment\local\tools, untracked), else PATH (the
# GitHub workflows: setup-zig, setup-python). arch_check / addrgen / docgen use the standard library only.
$tools = Join-Path $here 'environment\local\tools'
$zig = (Get-ChildItem (Join-Path $tools 'zig*\zig.exe') -ErrorAction SilentlyContinue | Select-Object -First 1).FullName
if (-not $zig) { $zig = (Get-Command zig -ErrorAction SilentlyContinue).Source }
if (-not $zig) { throw "zig not found: in environment\local\tools\zig*\ or on PATH" }
$winInc = Join-Path (Split-Path -Parent $zig) 'lib\libc\include\any-windows-any'
$PythonExe = Join-Path $tools 'python\python.exe'
if (-not (Test-Path $PythonExe)) { $PythonExe = (Get-Command python -ErrorAction SilentlyContinue).Source }
if (-not $PythonExe) { throw "Python not found: in environment\local\tools\python\ or on PATH" }

# Architecture rules first (docs/architecture.md): a violation stops the build.
& $PythonExe -I (Join-Path $here 'tools\arch_check.py')
if ($LASTEXITCODE -ne 0) { throw "arch_check failed: fix the code (rules + reasons: docs/architecture.md, docs/decisions.md)" }

# The address table is compiled in: regenerate the header from addresses.json.
& $PythonExe -I (Join-Path $here 'tools\addrgen.py') header (Join-Path $here 'core\gen\addresses_gen.h')
if ($LASTEXITCODE -ne 0) { throw "addrgen header failed ($LASTEXITCODE)" }
# ... and the Debug override fixtures the address tests load (D61): the table with one change each.
& $PythonExe -I (Join-Path $here 'tools\make_override_fixtures.py') | Out-Null
if ($LASTEXITCODE -ne 0) { throw "make_override_fixtures failed ($LASTEXITCODE)" }

# Core services in core/, one folder per feature module in features/ (self-registered, see core/modules.h).
$features = Get-ChildItem (Join-Path $here 'features') -Directory |
    Where-Object { $d = $_.Name; -not ($Without | Where-Object { $d -like $_ }) }
$sources = @(Get-ChildItem (Join-Path $here 'core') -Filter *.cpp) +
    @($features | ForEach-Object { Get-ChildItem $_.FullName -Filter *.cpp }) | ForEach-Object FullName
if ($Without) { "without: $($Without -join ', ') -> $(@($sources | Where-Object { $_ -like '*\features\*' }).Count) feature file(s) left" }

# Distinct preferred base: Genesis.dll and the other .asi files sit at
# 0x10000000 / 0x3C000000. Relocatable regardless (--dynamicbase).
$common = @(
    'c++', '-target', 'x86-windows-gnu', '-shared', '-std=c++17',
    '-fno-rtti', '-fno-exceptions', '-fno-stack-protector', '-fno-builtin',
    '-fno-threadsafe-statics',   # no CRT guard functions; function-local statics are game-thread only
    '-nostdlib', '-Wall', '-Wextra', '-Werror', '-Wno-nullability-completeness',
    '-Wno-unused-command-line-argument',   # zig injects -fno-rtlib-defaultlib itself
    '-Wglobal-constructors', '-Wexit-time-destructors',  # arch rule R7: no CRT runs them (docs/architecture.md)
    '-isystem', $winInc,
    '-I', (Join-Path $here 'core'),
    '-Wl,--image-base,0x3D000000', '-Wl,--dynamicbase'
)
# Single source of the core version (also read by the harness for {core_version}).
$version = (Get-Content (Join-Path $here 'VERSION') -Raw).Trim()
[IO.File]::WriteAllText((Join-Path $here 'core\gen\version_gen.h'),
    "// GENERATED by build.ps1 from VERSION -- do not edit.`n#pragma once`n#define FDCORE_VERSION `"$version`"`n")

$perConfig = @{
    # zig enables UBSan at -O0; there's no sanitizer runtime in a no-CRT DLL.
    Debug   = @('-O0', '-g', '-fno-sanitize=all', '-DFDCORE_DEBUG=1')
    Release = @('-O2')
}
$configs = if ($Config -eq 'Both') { 'Debug', 'Release' } else { @($Config) }

# MinHook (vendored, thirdparty/minhook) is C: compiled separately with
# `zig cc`, statically linked. Not our code, so no -Werror on it.
$mhDir = Join-Path $here 'thirdparty\minhook\src'
$mhSources = @('hook.c', 'buffer.c', 'trampoline.c', 'hde\hde32.c') | ForEach-Object { Join-Path $mhDir $_ }

foreach ($c in $configs) {
    $outDir = Join-Path $here ("build\$c" + $(if ($Without) { '-without' } else { '' }))
    $objDir = Join-Path $outDir 'obj'
    New-Item -ItemType Directory -Force -Path $objDir | Out-Null
    $out = Join-Path $outDir 'FDNYCore.asi'

    $objs = @()
    foreach ($s in $mhSources) {
        $o = Join-Path $objDir ([IO.Path]::GetFileNameWithoutExtension($s) + '.o')
        $ccArgs = @('cc', '-target', 'x86-windows-gnu', '-c', '-fno-stack-protector', '-fno-builtin',
                    '-fno-sanitize=all', '-isystem', $winInc, '-Wno-unused-command-line-argument') +
                  $perConfig[$c].Where({ $_ -notlike '-DFDCORE*' }) + @('-o', $o, $s)
        & $zig @ccArgs
        if ($LASTEXITCODE -ne 0) { throw "$c MinHook build failed on $s ($LASTEXITCODE)" }
        $objs += $o
    }

    $args = $common + $perConfig[$c] + @('-o', $out) + $sources + $objs + @('-lkernel32', '-luser32', '-lgdi32', '-lbcrypt')
    & $zig @args
    if ($LASTEXITCODE -ne 0) { throw "$c build failed ($LASTEXITCODE)" }

    $b = [System.IO.File]::ReadAllBytes($out)
    $pe = [BitConverter]::ToInt32($b, 0x3C)
    $mach = [BitConverter]::ToUInt16($b, $pe + 4)
    "built $c\FDNYCore.asi  $([math]::Round($b.Length / 1KB, 1)) KB  machine=0x$('{0:X}' -f $mach)"
    if ($mach -ne 0x14C) { throw "$c build is not x86 (machine 0x$('{0:X}' -f $mach))" }

    # The player reference, read from the same source (a registration it can't read stops the build).
    & $PythonExe -I (Join-Path $here 'tools\docgen.py') sheet (Join-Path $outDir 'quick-reference.md') --asi $out
    if ($LASTEXITCODE -ne 0) { throw "docgen failed: see above (tools/docgen.py explains what it reads)" }
}

# The source's own reference: docs/quick-reference.md (tracked; the pre-commit hook also rewrites
# and stages it).
if (-not $Without) {
    & $PythonExe -I (Join-Path $here 'tools\docgen.py') sheet (Join-Path $here 'docs\quick-reference.md')
    if ($LASTEXITCODE -ne 0) { throw "docgen failed: see above" }
}
